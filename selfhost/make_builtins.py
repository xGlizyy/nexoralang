"""Writes selfhost/builtins.nex: the built-in functions as `nex symbols` lists them (nexora.symbols/2, `builtins`).

    PYTHONPATH=nexora/src python selfhost/make_builtins.py

It is generated from the Python tables (tooling._builtin_entries), like info.nex: run it again when a built-in changes.
"""

import json
import pathlib

from nexora import tooling


def main():
    text = json.dumps(tooling._builtin_entries(), ensure_ascii=False, separators=(",", ":"))
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("{", r"\{")
    target = pathlib.Path(__file__).with_name("builtins.nex")
    target.write_text(
        "// The built-in functions as `nex symbols` lists them: a JSON text, read when it is needed.\n"
        "// Generated by selfhost/make_builtins.py: do not edit it by hand.\n\n"
        "pub fn builtins_text() gives Text {\n"
        f'    return "{escaped}"\n'
        "}\n",
        encoding="utf-8", newline="\n",
    )


if __name__ == "__main__":
    main()
