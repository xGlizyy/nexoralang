"""Writes selfhost/runtime_text.nex from selfhost/runtime/nexora_rt.h.

    python selfhost/make_runtime.py

The generator (cgen.nex) puts the runtime at the top of every C file it writes, and a NEXORA program cannot read a file that
is not declared next to it at run time without the user allowing it, so the text of the header goes into the generator as
data, one line at a time. Run this again after changing the header.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent


def quoted(line: str) -> str:
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"').replace("{", "\\{").replace("\t", "\\t") + '"'


def main() -> None:
    lines = (HERE / "runtime" / "nexora_rt.h").read_text(encoding="utf-8").split("\n")
    out = [
        "// The runtime of the C that cgen.nex writes, as text. Generated by selfhost/make_runtime.py from",
        "// selfhost/runtime/nexora_rt.h: do not edit it by hand.",
        "",
        "pub fn runtime_lines() gives List[Text] {",
        "    var lines: List[Text] = []",
    ]
    out += [f"    lines = List.append(lines, {quoted(line)})" for line in lines]
    out += ["    return lines", "}", ""]
    (HERE / "runtime_text.nex").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(lines)} lines")


if __name__ == "__main__":
    main()
