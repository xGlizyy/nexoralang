"""Writes selfhost/lsp_tables.nex: what the language server offers that comes from the tables of Python.

    PYTHONPATH=nexora/src python selfhost/make_lsp_tables.py

The keywords, the reserved words and the built-in functions (name, signature and parameters) as a JSON text, like builtins.nex and
info.nex: run it again when one of them changes.
"""

import json
import pathlib

from nexora.checker import BUILTINS
from nexora.tokens import KEYWORDS, RESERVED_WORDS


def main():
    data = {
        "keywords": sorted(KEYWORDS),
        "reserved": sorted(RESERVED_WORDS),
        "builtins": [
            {"name": name, "signature": BUILTINS[name].describe(), "params": [[label, kind or ""] for label, kind in BUILTINS[name].params]}
            for name in sorted(BUILTINS)
        ],
    }
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("{", r"\{")
    target = pathlib.Path(__file__).with_name("lsp_tables.nex")
    target.write_text(
        "// What the language server offers from the tables of the language: a JSON text, read when it is needed.\n"
        "// Generated by selfhost/make_lsp_tables.py: do not edit it by hand.\n\n"
        "pub fn tables_text() gives Text {\n"
        f'    return "{escaped}"\n'
        "}\n",
        encoding="utf-8", newline="\n",
    )


if __name__ == "__main__":
    main()
