"""Writes selfhost/info.nex: the answer of the `info` action of the worker, from the Python implementation.

    PYTHONPATH=nexora/src python selfhost/make_info.py

The keywords, the reserved words, the types and the builtins are data of the language (nexora/src/nexora/api.py,
`language_info`), and the worker written in NEXORA answers `info` with them. The file is generated so that the two never
differ by hand; run this again when the language changes.
"""

from __future__ import annotations

import json
from pathlib import Path

from nexora import api
from nexora.version import __version__

HERE = Path(__file__).resolve().parent


def quoted(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("{", r"\{") + '"'


def main() -> None:
    response = {"schema": api.RESULT_SCHEMA, "action": "info", "status": api.SUCCESS, **api.language_info()}
    lines = [
        "// What the worker answers to `info`, and the version of the language, as nexora/src/nexora/api.py gives them.",
        "// Generated by selfhost/make_info.py: do not edit it by hand.",
        "",
        "pub fn version() gives Text {",
        f"    return {quoted(__version__)}",
        "}",
        "",
        "pub fn answer() gives Text {",
        f"    return {quoted(json.dumps(response, ensure_ascii=False))}",
        "}",
        "",
    ]
    (HERE / "info.nex").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"version {__version__}")


if __name__ == "__main__":
    main()
