"""Writes selfhost/mcp_tables.nex: what the MCP server of NEXORA answers that does not depend on the program it is given.

    MCP_PYTHON=path/to/python-with-the-mcp-sdk PYTHONPATH=nexora/src python selfhost/make_mcp_tables.py

* the description of the tools (name, description, schemas and annotations), exactly as the SDK of MCP writes them for the server of
  Python (`tools/list`): they are made from the signatures of the Python functions, so they are asked of the real server;
* the instructions of the server, the capabilities of this version of NEXORA (`nexora_get_capabilities`) and the text of the
  specification of the language (`nexora_get_language_spec`), which the Python server reads from the documentation of a checkout.

Run it again when a tool, a built-in function, a diagnostic code or the specification changes.
"""

import json
import os
import pathlib
import re
import subprocess
import sys

from nexora import mcp_server, tooling


def escaped(text: str) -> str:
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "{":
            out.append("\\{")
        elif char == "\n":
            out.append("\\n")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 32:
            raise SystemExit(f"a control character U+{ord(char):04X} cannot be written in a text literal")
        else:
            out.append(char)
    return "".join(out)


def tools_of_server() -> list:
    python = os.environ.get("MCP_PYTHON")
    if not python:
        raise SystemExit("set MCP_PYTHON to a Python that has the MCP SDK")
    sys.path.insert(0, str(pathlib.Path(__file__).parent))
    from compare_mcp import Client

    client = Client([python, "-m", "nexora.mcp_server"], dict(os.environ, PYTHONUTF8="1"))
    try:
        client.ask({"jsonrpc": "2.0", "id": 1, "method": "initialize",
                    "params": {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "tables", "version": "1"}}})
        client.ask({"jsonrpc": "2.0", "method": "notifications/initialized"})
        answer = client.ask({"jsonrpc": "2.0", "id": 2, "method": "tools/list"})
    finally:
        client.close()
    return answer["result"]["tools"]


def chunks(text: str, size: int = 4000) -> list[str]:
    """The text cut at line ends into pieces of about `size` characters."""
    parts, current = [], ""
    for line in text.split("\n"):
        if len(current) + len(line) + 1 > size and current:
            parts.append(current)
            current = ""
        current += line + "\n"
    parts.append(current[:-1])
    return parts


def slices(text: str, size: int) -> list[str]:
    """The text cut into pieces of `size` characters (a JSON text has no line ends to cut at)."""
    return [text[at:at + size] for at in range(0, len(text), size)] or [""]


def literal(text: str) -> str:
    return f'"{escaped(text)}"'


def main():
    tools = json.dumps(tools_of_server(), ensure_ascii=False, separators=(",", ":"))
    capabilities = json.dumps(tooling.get_capabilities(), ensure_ascii=False, separators=(",", ":"))
    spec = tooling._SPEC_PATH.read_text(encoding="utf-8")
    assert "\r" not in spec
    pieces = ",\n        ".join(literal(piece) for piece in chunks(spec))
    capability_pieces = ",\n        ".join(literal(piece) for piece in slices(capabilities, 6000))
    tool_pieces = ",\n        ".join(literal(piece) for piece in slices(tools, 6000))
    sections = tooling._spec_sections(spec)
    lines = spec.split("\n")
    index = []
    for position, section in enumerate(sections):
        end = len(lines)
        for later in sections[position + 1:]:
            if later["level"] <= section["level"]:
                end = later["start"]
                break
        index.append({"id": section["id"], "title": section["title"], "level": section["level"], "start": section["start"], "end": end})
    version = re.search(r"\*\*Specification version:\*\*\s*([\d.]+)", spec)
    index_text = json.dumps({"spec_version": version.group(1) if version else None, "sections": index}, ensure_ascii=False, separators=(",", ":"))
    index_pieces = ",\n        ".join(literal(piece) for piece in slices(index_text, 6000))
    text = (
        "// What the MCP server answers that does not depend on the program it is given.\n"
        "// Generated by selfhost/make_mcp_tables.py: do not edit it by hand.\n\n"
        "// The tools, as `tools/list` gives them: a JSON text.\n"
        f"pub fn tools_parts() gives List[Text] {{\n    return (\n    [\n        {tool_pieces}\n    ]\n    )\n}}\n\n"
        "// What the server says about itself.\n"
        f"pub fn instructions() gives Text {{\n    return {literal(mcp_server.INSTRUCTIONS)}\n}}\n\n"
        "// The facts about this version of NEXORA (`nexora_get_capabilities`): a JSON text.\n"
        f"pub fn capabilities_parts() gives List[Text] {{\n    return (\n    [\n        {capability_pieces}\n    ]\n    )\n}}\n\n"
        "// Where the sections of the specification are: a JSON text with the version and, for each section, its id, title, level and lines.\n"
        f"pub fn spec_index_parts() gives List[Text] {{\n    return (\n    [\n        {index_pieces}\n    ]\n    )\n}}\n\n"
        "// The specification of the language (docs/language-spec.md), in pieces that end where a line ends.\n"
        f"pub fn spec_parts() gives List[Text] {{\n    return (\n    [\n        {pieces}\n    ]\n    )\n}}\n"
    )
    pathlib.Path(__file__).with_name("mcp_tables.nex").write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
