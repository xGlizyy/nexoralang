"""Writes selfhost/unicode_tables.nex: which characters Python calls letters and which it calls printable.

    PYTHONPATH=nexora/src python selfhost/make_unicode_tables.py

The lexer shows a character it does not know as 'c' when `str.isprintable()` is true and as U+XXXX when it is not, and it adds a
hint when `str.isalpha()` is true (nexora/src/nexora/lexer.py). The tables are the ranges of the code points above 127 for which
each of the two is true, as flat lists [first, last, first, last, ...]; they depend on the version of Unicode of the Python that
generates them (the one of the reference implementation).
"""

import pathlib
import sys


def ranges(test) -> list[int]:
    out: list[int] = []
    start = None
    for code in range(128, sys.maxunicode + 2):
        hit = code <= sys.maxunicode and test(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            out.extend([start, code - 1])
            start = None
    return out


def function(name: str, comment: str, values: list[int]) -> str:
    rows = []
    for at in range(0, len(values), 16):
        rows.append("        " + ", ".join(str(value) for value in values[at:at + 16]))
    body = ",\n".join(rows)
    return f"// {comment}\npub fn {name}() gives List[Int] {{\n    return (\n    [\n{body}\n    ]\n    )\n}}\n"


def main():
    alpha = ranges(lambda c: c.isalpha())
    alnum = ranges(lambda c: c.isalnum())
    unprintable = ranges(lambda c: not c.isprintable())
    text = (
        "// Which characters above 127 are letters and which are not printable, for the messages of the lexer.\n"
        "// Generated by selfhost/make_unicode_tables.py from the Unicode data of Python: do not edit it by hand.\n\n"
        + function("letters", "The code points for which Python's str.isalpha() is true, as first and last of each range.", alpha)
        + "\n"
        + function("alphanumeric", "The code points for which Python's str.isalnum() is true (what \\w matches), as first and last of each range.", alnum)
        + "\n"
        + function("unprintable", "The code points for which Python's str.isprintable() is false, as first and last of each range.", unprintable)
    )
    pathlib.Path(__file__).with_name("unicode_tables.nex").write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
