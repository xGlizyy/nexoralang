"""Writes selfhost/titles.nex from the table of diagnostics of the Python implementation.

    PYTHONPATH=nexora/src python selfhost/make_titles.py

The title and the category of each code are data of the language (nexora/src/nexora/diagnostics.py), and nex.nex shows
them in front of every message. The file is generated so that the two never differ by hand; run this again when a code is
added.
"""

from __future__ import annotations

from pathlib import Path

from nexora.diagnostics import _REGISTRY

HERE = Path(__file__).resolve().parent


def quoted(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("{", "\\{") + '"'


def main() -> None:
    lines = [
        "// The title and the category of each diagnostic code, as nexora/src/nexora/diagnostics.py declares them.",
        "// Generated by selfhost/make_titles.py: do not edit it by hand.",
        "",
        "pub fn title_of(code: Text) gives Text {",
    ]
    for code, (title, _) in _REGISTRY.items():
        lines += [f"    if code == {quoted(code)} {{", f"        return {quoted(title)}", "    }"]
    lines += ['    return ""', "}", "", "pub fn category_of(code: Text) gives Text {"]
    for code, (_, category) in _REGISTRY.items():
        lines += [f"    if code == {quoted(code)} {{", f"        return {quoted(category)}", "    }"]
    lines += ['    return "runtime"', "}", ""]
    (HERE / "titles.nex").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(_REGISTRY)} codes")


if __name__ == "__main__":
    main()
